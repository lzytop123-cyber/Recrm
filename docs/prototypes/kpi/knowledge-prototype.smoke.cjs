// Run with Node and PLAYWRIGHT_PATH pointing to an installed Playwright module.
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
let browser;
(async () => {
  browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage();
  const errors = [], externalRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/^https?:/.test(request.url())) externalRequests.push(request.url()); });
  const url = pathToFileURL(path.join(__dirname, 'frontend.html')).href;
  const open = async () => {
    await page.goto(url);
    await page.getByRole('heading', { name: '企业知识库', exact: true }).waitFor();
  };
  for (const [size, width, height] of [['desktop', 1920, 1080], ['tablet', 820, 1000], ['mobile', 390, 844]]) {
    await page.setViewportSize({ width, height });
    await open();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), size + ' viewport overflow');
    await page.screenshot({ path: path.join(__dirname, `knowledge-prototype-${size}.png`), fullPage: size === 'mobile' });
    const search = page.getByRole('searchbox', { name: '搜索文档' });
    await search.fill('完全不存在的文档');
    await page.getByRole('heading', { name: '没有找到匹配的文档' }).waitFor();
    await page.getByRole('button', { name: '清除筛选', exact: true }).first().click();
    await page.getByRole('button', { name: '审批流程与权限确认清单', exact: true }).click();
    const drawer = page.getByRole('dialog');
    await drawer.getByRole('heading', { name: '来源与附件', exact: true }).waitFor();
    if (size === 'desktop') await page.screenshot({ path: path.join(__dirname, 'knowledge-prototype-reading.png') });
    await page.keyboard.press('Escape');
    await drawer.waitFor({ state: 'hidden' });
    if (size === 'mobile') await page.getByRole('combobox', { name: '选择知识目录' }).selectOption('合规知识');
    else await page.getByRole('button', { name: /^合规知识/ }).click();
    await search.fill('保密');
    assert.equal(await page.locator('[data-document-id]').count(), 1);
    await page.getByRole('button', { name: '清除筛选', exact: true }).first().click();
    if (size === 'mobile') await page.getByRole('combobox', { name: '选择知识目录' }).selectOption('全部文档');
    else await page.getByRole('button', { name: /^全部文档/ }).click();
    await page.getByRole('combobox', { name: '文档状态', exact: true }).selectOption('published');
    assert.ok(await page.locator('[data-document-id]').count() > 0);
    assert.equal(await page.locator('.kb-results .kb-status.pending_review').count(), 0);
    await page.getByRole('button', { name: '清除筛选', exact: true }).first().click();
    await page.getByRole('button', { name: '下一页', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: '第 2 页', exact: true }).getAttribute('aria-current'), 'page');
    if (size !== 'mobile') {
      await page.getByRole('button', { name: '卡片视图' }).click();
      assert.ok(await page.locator('.kb-card').count() > 0);
    }
    console.log(size + ': search, catalog/status filters, pagination, reading and responsive layout passed');
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await open();
  await page.getByRole('button', { name: '新建文档', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '提交审核', exact: true }).click();
  await page.getByText('请填写文档标题。', { exact: true }).waitFor();
  await page.getByRole('textbox', { name: '文档标题', exact: true }).fill('原型回归：交接指南');
  await page.getByRole('textbox', { name: '文档内容', exact: true }).fill('交接前确认负责人、资料清单和完成时间。');
  await page.getByRole('button', { name: '保存草稿', exact: true }).click();
  const draftRow = page.locator('[data-document-id]').filter({ hasText: '原型回归：交接指南' });
  await draftRow.locator('summary').click();
  await draftRow.getByRole('button', { name: '提交审核', exact: true }).click();
  await page.getByRole('navigation', { name: '知识库页面' }).getByRole('button', { name: /^审核管理/ }).click();
  await page.getByRole('searchbox', { name: '搜索文档' }).fill('原型回归：交接指南');
  await page.getByRole('button', { name: '原型回归：交接指南', exact: true }).click();
  await page.getByRole('button', { name: '确认发布', exact: true }).click();
  await page.getByRole('navigation', { name: '知识库页面' }).getByRole('button', { name: '文档中心', exact: true }).click();
  const publishedRow = page.locator('[data-document-id]').filter({ hasText: '原型回归：交接指南' });
  assert.equal(await publishedRow.locator('.kb-status').textContent(), '已发布');
  await publishedRow.locator('summary').click();
  await publishedRow.getByRole('button', { name: '删除文档', exact: true }).click();
  await page.getByRole('button', { name: '确认删除', exact: true }).click();
  await page.getByRole('button', { name: '同步飞书', exact: true }).click();
  await page.getByRole('button', { name: '开始同步', exact: true }).click();
  await page.getByRole('button', { name: '飞书同步：团队协作与交接指南', exact: true }).click();
  await page.getByRole('button', { name: '退回修改', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '退回修改', exact: true }).click();
  await page.getByText('请填写修改意见，便于作者处理。', { exact: true }).waitFor();
  await page.getByRole('textbox', { name: '修改意见', exact: true }).fill('请补充责任人与交接资料清单。');
  await page.getByRole('dialog').getByRole('button', { name: '退回修改', exact: true }).click();
  await page.getByRole('button', { name: '新建目录', exact: true }).first().click();
  await page.getByRole('textbox', { name: '目录名称', exact: true }).fill('客户案例');
  await page.getByRole('dialog').getByRole('button', { name: '新建目录', exact: true }).click();
  await page.getByRole('heading', { name: '这个目录还没有文档', exact: true }).waitFor();
  await open();
  await page.getByRole('navigation', { name: '知识库页面' }).getByRole('button', { name: /^审核管理/ }).click();
  await page.screenshot({ path: path.join(__dirname, 'knowledge-prototype-audit.png'), fullPage: false });
  await page.goto(url + '?view=kpi&experience=classic');
  await page.locator('.sidebar').waitFor();
  assert.ok(await page.locator('h1').count() > 0, 'existing KPI prototype renders');
  await page.locator('.sidebar button.navbutton').nth(1).click();
  await page.getByRole('link', { name: '企业知识库原型', exact: true }).click();
  await page.getByRole('heading', { name: '企业知识库', exact: true }).waitFor();
  assert.deepEqual(errors, []);
  assert.deepEqual(externalRequests, [], 'prototype must not access external services');
  console.log('Draft validation/submission, publish/delete, simulated sync, rejection, new catalog and existing KPI entry passed.');
  await browser.close();
})().catch(async error => { console.error(error); await browser?.close(); process.exitCode = 1; });
