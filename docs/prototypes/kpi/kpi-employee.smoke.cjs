const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
let browser;
(async () => {
  browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.setDefaultTimeout(5000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const url = pathToFileURL(path.join(__dirname, 'frontend.html')).href + '?view=kpi&page=self';
  await page.goto(url);
  await page.getByRole('heading', { name: '我的考核', exact: true }).waitFor();
  await page.getByRole('button', { name: '提交主管', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '请补齐' }).waitFor();
  assert.equal(await page.getByRole('dialog').count(), 0);
  await page.getByLabel('有效线索与签约实际完成情况', { exact: true }).fill('有效线索 21 条 / 签约 3 家');
  await page.getByLabel('有效线索与签约成果说明', { exact: true }).fill('完成线索21条，签约3家，附客户成果记录。');
  await page.getByLabel('有效线索与签约成果链接', { exact: true }).fill('https://example.com/evidence');
  await page.getByLabel('客户跟进质量实际完成情况', { exact: true }).fill('跟进及时率 95.8%');
  await page.getByLabel('客户跟进质量成果说明', { exact: true }).fill('跟进及时率95.8%，已核对跟进台账。');
  await page.getByLabel('协作与工作规范实际完成情况', { exact: true }).fill('按期完成5项协作任务');
  await page.getByLabel('协作与工作规范成果说明', { exact: true }).fill('按时完成跨部门协作，按要求留存工作记录。');
  await page.getByLabel('本月工作总结', { exact: true }).fill('本月签约目标仍有差距，后续加强重点客户跟进。');
  await page.getByRole('button', { name: '保存草稿', exact: true }).click();
  await page.reload();
  assert.ok((await page.getByLabel('本月工作总结', { exact: true }).inputValue()).includes('重点客户'));
  assert.equal(await page.getByLabel('有效线索与签约实际完成情况', { exact: true }).inputValue(), '有效线索 21 条 / 签约 3 家');
  assert.equal(await page.getByLabel('有效线索与签约实际完成情况', { exact: true }).getAttribute('readonly'), null);
  await page.getByLabel('有效线索与签约成果附件', { exact: true }).setInputFiles({ name: 'bad.exe', mimeType: 'application/octet-stream', buffer: Buffer.from('invalid') });
  await page.getByRole('alert').filter({ hasText: '类型不支持' }).waitFor();
  await page.getByLabel('有效线索与签约成果链接', { exact: true }).fill('');
  await page.getByLabel('有效线索与签约成果附件', { exact: true }).setInputFiles({ name: '签约证明.pdf', mimeType: 'application/pdf', buffer: Buffer.from('prototype file metadata') });
  await page.getByRole('button', { name: '保存草稿', exact: true }).click();
  await page.reload();
  await page.getByText('需重新选择文件', { exact: true }).waitFor();
  await page.getByRole('checkbox', { name: '我已核对填报内容和成果材料，确认真实完整' }).check();
  await page.getByRole('button', { name: '提交主管', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '请补齐' }).waitFor();
  await page.getByLabel('有效线索与签约成果链接', { exact: true }).fill('https://example.com/evidence');
  await page.locator('.ks-editor').evaluate(node => node.scrollTop = 0);
  await page.screenshot({ style: '.notice { visibility: hidden !important; }', path: path.join(__dirname, 'kpi-employee-desktop.png') });
  await page.getByLabel('有效线索与签约成果链接', { exact: true }).fill('javascript:alert(1)');
  await page.getByRole('checkbox', { name: '我已核对填报内容和成果材料，确认真实完整' }).check();
  await page.getByRole('button', { name: '提交主管', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'http' }).waitFor();
  await page.getByLabel('有效线索与签约成果链接', { exact: true }).fill('https://example.com/evidence');
  await page.getByRole('button', { name: '提交主管', exact: true }).click();
  await page.getByRole('dialog', { name: '确认提交考核', exact: true }).waitFor();
  await page.getByRole('button', { name: '确认提交', exact: true }).click();
  await page.getByRole('heading', { name: '已提交，等待主管评分', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: '提交主管', exact: true }).count(), 0);
  await page.screenshot({ style: '.notice { visibility: hidden !important; }', path: path.join(__dirname, 'kpi-employee-submitted.png') });
  await page.getByRole('button', { name: '管理员视角', exact: true }).click();
  await page.getByRole('searchbox', { name: '搜索考核人员' }).fill('张明');
  await page.getByRole('button', { name: '查询', exact: true }).click();
  await page.getByRole('button', { name: '查看详情', exact: true }).click();
  assert.ok((await page.getByRole('dialog').innerText()).includes('签约3家'));
  assert.equal(await page.getByRole('button', { name: '提交主管评分', exact: true }).count(), 0, 'HR cannot score as manager');
  await page.keyboard.press('Escape');
  await page.getByRole('combobox', { name: '原型体验身份' }).selectOption('manager');
  await page.locator('[data-team-person="person-0-0"]').getByRole('button', { name: '去评分' }).click();
  await page.getByRole('button', { name: '退回补充', exact: true }).click();
  await page.getByLabel('退回原因', { exact: true }).fill('签约成果链接需要补充客户名称和验收说明。');
  await page.getByRole('button', { name: '确认退回', exact: true }).click();
  await page.keyboard.press('Escape');
  await page.getByRole('combobox', { name: '原型体验身份' }).selectOption('employee');
  await page.getByRole('button', { name: '我的考核', exact: true }).click();
  await page.getByText('签约成果链接需要补充客户名称和验收说明。', { exact: true }).waitFor();
  assert.ok((await page.getByLabel('有效线索与签约成果说明', { exact: true }).inputValue()).includes('签约3家'));
  for (const [name, width, height] of [['laptop',1366,768], ['mobile',390,844]]) {
    await page.setViewportSize({ width, height });
    const d = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, height: innerHeight, scrollHeight: document.documentElement.scrollHeight, footer: document.querySelector('.ks-footer').getBoundingClientRect().bottom }));
    assert.ok(d.scrollWidth <= d.width + 1, name + ' horizontal overflow');
    assert.ok(d.footer <= d.height + 1, name + ' fixed actions remain visible');
    if (width > 960) assert.ok(d.scrollHeight <= d.height + 1, name + ' desktop page fits');
    await page.screenshot({ style: '.notice { visibility: hidden !important; }', path: path.join(__dirname, 'kpi-employee-' + name + '.png') });
  }
  assert.deepEqual(errors, []);
  console.log('Employee draft recovery, immutable rules, validation, submission, manager return, preserved content and responsive layout passed');
  await browser.close();
})().catch(async e => { console.error(e); await browser?.close(); process.exitCode = 1; });
