const assert=require('node:assert/strict');
const pm=require('./personnel-matching.js');
const roster=pm.demoRoster();
const template={id:'demo',department:'市场部',role:'市场业务'};
const result=pm.matchPersonnel(roster,template,{month:'2026-09'},{includeProbation:false,minDays:15},['u3|demo|2026-09']);
assert.deepEqual(result.matched.map(x=>x.name),['张明','王芳','何杰']);
assert.equal(result.blocked.find(x=>x.name==='李强').reason,'本周期已存在该模板考核');
assert.equal(result.excluded.find(x=>x.name==='赵敏').reason,'试用期不参加月度考核');
assert.equal(result.excluded.find(x=>x.name==='孙悦').reason,'本月在岗10天，少于15天');
assert.equal(result.excluded.find(x=>x.name==='刘川').reason,'长期休假');
assert.equal(result.all.some(x=>x.name==='李梅'),false,'岗位不匹配人员不进入候选池');
assert.deepEqual(pm.validateSelection(result,['u1','u2','u12'],{}),[]);
assert.ok(pm.validateSelection(result,['u1'],{}).some(x=>x.includes('王芳')));
assert.deepEqual(pm.validateSelection(result,['u1'],{u2:'当月长期外派，不参与本期考核',u12:'临时借调'}),[]);
assert.ok(pm.validateSelection(result,['u1','u2','u12','u4'],{}).some(x=>x.includes('赵敏')));
assert.deepEqual(pm.validateSelection(result,['u1','u2','u12','u4'],{u4:'部门确认试用期仍参加月度考核'}),[]);
assert.ok(pm.validateSelection(result,['u1','u3'],{u2:'外派',u12:'借调'}).some(x=>x.includes('重复')));
const snapshots=pm.buildSnapshots(result,['u1','u2','u12','u4'],{u4:'部门确认试用期仍参加月度考核'});
assert.equal(snapshots[0].department,'市场部');
assert.equal(snapshots.find(x=>x.id==='u4').adjustmentType,'manual_include');
assert.equal(snapshots.find(x=>x.id==='u4').adjustmentReason,'部门确认试用期仍参加月度考核');
console.log('Personnel matching, exclusions, duplicate blocking, manual adjustment reasons and snapshots passed');
