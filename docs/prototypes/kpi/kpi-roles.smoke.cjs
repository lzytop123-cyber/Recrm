const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
let browser;
(async () => {
  browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.setDefaultTimeout(5000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const url = pathToFileURL(path.join(__dirname, 'frontend.html')).href + '?view=kpi';
  const role = value => page.getByRole('combobox', { name: '原型体验身份' }).selectOption(value);
  await page.addInitScript(() => {
    window.__originalFrame = window.requestAnimationFrame.bind(window);
    window.__heldRenders = [];
    window.requestAnimationFrame = callback => callback.name === 'renderRows'
      ? (window.__heldRenders.push(callback), window.__originalFrame(() => {}))
      : window.__originalFrame(callback);
  });
  const score = async (first, note) => {
    await page.getByLabel('有效线索与签约主管得分', { exact: true }).fill(String(first));
    await page.getByLabel('客户跟进质量主管得分', { exact: true }).fill('27');
    await page.getByLabel('协作与工作规范主管得分', { exact: true }).fill('18');
    await page.getByLabel('评分依据与改进建议', { exact: true }).fill(note);
    await page.getByRole('checkbox', { name: '我已核实员工材料，并按本期模板标准评分' }).check();
  };
  await page.goto(url);
  await page.getByRole('heading', { name: 'KPI 考核', exact: true }).waitFor();
  await page.waitForFunction(() => window.__heldRenders.length > 0);
  await role('manager');
  await page.evaluate(() => {
    window.__heldRenders.splice(0).forEach(callback => callback());
    window.requestAnimationFrame = window.__originalFrame;
  });
  assert.equal(await page.locator('[data-person-id]').count(), 0, 'stale admin refresh cannot replace manager rows');
  assert.equal(await page.locator('[data-team-person]').count(), 1);
  await role('employee');
  assert.equal(await page.getByRole('button', { name: '考核模板管理', exact: true }).count(), 0);
  assert.equal(await page.getByRole('heading', { name: '我的考核', exact: true }).count(), 1);
  await page.getByLabel('有效线索与签约实际完成情况', { exact: true }).fill('有效线索 21 条 / 签约 3 家');
  await page.getByLabel('有效线索与签约成果说明', { exact: true }).fill('线索21条，签约3家，已补充签约证明。');
  await page.getByLabel('有效线索与签约成果链接', { exact: true }).fill('https://example.com/result');
  await page.getByLabel('客户跟进质量实际完成情况', { exact: true }).fill('跟进及时率 95.8%');
  await page.getByLabel('客户跟进质量成果说明', { exact: true }).fill('跟进及时率95.8%，按台账核对。');
  await page.getByLabel('协作与工作规范实际完成情况', { exact: true }).fill('完成5项协作任务');
  await page.getByLabel('协作与工作规范成果说明', { exact: true }).fill('按时交付，工作记录完整。');
  await page.getByLabel('本月工作总结', { exact: true }).fill('本月成果已核对，下月加强签约转化。');
  await page.getByRole('checkbox', { name: '我已核对填报内容和成果材料，确认真实完整' }).check();
  await page.getByRole('button', { name: '提交主管', exact: true }).click();
  await page.getByRole('button', { name: '确认提交', exact: true }).click();
  await role('manager');
  await page.getByRole('heading', { name: '团队考核', exact: true }).waitFor();
  await page.getByRole('button', { name: '全部团队 6', exact: true }).click();
  assert.equal(await page.locator('[data-team-person]').count(), 6);
  assert.ok(!(await page.locator('.kp-results').innerText()).includes('陈浩'), 'manager cannot view another supervisor team');
  assert.equal(await page.getByRole('button', { name: '发起考核', exact: true }).count(), 0);
  await page.screenshot({ style: '.notice { visibility: hidden !important; }', path: path.join(__dirname, 'kpi-manager-team.png') });
  await page.locator('[data-team-person="person-0-0"]').getByRole('button', { name: '去评分' }).click();
  await page.getByRole('heading', { name: '主管评分', exact: true }).waitFor();
  await page.getByRole('button', { name: '提交评分', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '完整填写' }).waitFor();
  await score(51, '核对材料后评分。');
  await page.getByRole('button', { name: '提交评分', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '不能超出' }).waitFor();
  await score(46, '依据本期达成情况和材料，拟评91分。');
  await page.getByRole('button', { name: '保存评分草稿', exact: true }).click();
  await page.locator('.ks-editor').evaluate(node => node.scrollTop = 0);
  await page.screenshot({ style: '.notice { visibility: hidden !important; }', path: path.join(__dirname, 'kpi-manager-scoring.png') });
  await page.getByRole('button', { name: '提交评分', exact: true }).click();
  await page.getByRole('button', { name: '确认提交评分', exact: true }).click();
  await role('admin');
  await page.getByRole('searchbox', { name: '搜索考核人员' }).fill('张明');
  await page.getByRole('button', { name: '查询', exact: true }).click();
  await page.getByRole('button', { name: '查看详情', exact: true }).click();
  await page.getByRole('button', { name: '退回主管', exact: true }).click();
  await page.getByLabel('退回评分原因', { exact: true }).fill('请核对第一项计分口径，补充评分依据。');
  await page.getByRole('button', { name: '确认退回评分', exact: true }).click();
  await page.keyboard.press('Escape');
  await role('manager');
  await page.locator('[data-team-person="person-0-0"]').getByRole('button', { name: '去评分' }).click();
  assert.equal(await page.getByLabel('有效线索与签约主管得分', { exact: true }).inputValue(), '46', 'HR return retains submitted scores');
  await page.getByText('请核对第一项计分口径，补充评分依据。', { exact: true }).waitFor();
  await score(47, '已重新核对计分口径并补充依据，合计92分。');
  await page.getByRole('button', { name: '提交评分', exact: true }).click();
  await page.getByRole('button', { name: '确认提交评分', exact: true }).click();
  await role('admin');
  await page.getByRole('searchbox', { name: '搜索考核人员' }).fill('张明');
  await page.getByRole('button', { name: '查询', exact: true }).click();
  await page.getByRole('button', { name: '查看详情', exact: true }).click();
  await page.getByLabel('HR复核意见', { exact: true }).fill('核对通过，交员工确认。');
  await page.getByRole('button', { name: '复核通过', exact: true }).click();
  await page.screenshot({ style: '.notice { visibility: hidden !important; }', path: path.join(__dirname, 'kpi-hr-review.png') });
  await page.keyboard.press('Escape');
  await role('employee');
  await page.getByRole('heading', { name: '评分已完成，请确认考核结果', exact: true }).waitFor();
  assert.ok((await page.locator('.ks-result-score').innerText()).includes('92'));
  await page.getByRole('button', { name: '确认考核结果', exact: true }).click();
  await page.getByRole('button', { name: '确认结果并归档', exact: true }).click();
  await page.getByRole('heading', { name: '本期考核已完成', exact: true }).waitFor();
  await page.screenshot({ style: '.notice { visibility: hidden !important; }', path: path.join(__dirname, 'kpi-employee-completed.png') });
  for (const [name,width,height] of [['laptop',1366,768],['mobile',390,844]]) {
    await page.setViewportSize({ width,height });
    await role('manager');
    await page.getByRole('button', { name: '全部团队 6', exact: true }).click();
    await page.locator('[data-team-person="person-0-1"]').getByRole('button', { name: '去评分' }).click();
    const dimensions = await page.evaluate(() => ({ width: innerWidth, sw: document.documentElement.scrollWidth, height: innerHeight, footer: document.querySelector('.ks-footer').getBoundingClientRect().bottom }));
    assert.ok(dimensions.sw <= dimensions.width + 1);
    assert.ok(dimensions.footer <= dimensions.height + 1);
    await page.screenshot({ style: '.notice { visibility: hidden !important; }', path: path.join(__dirname, 'kpi-manager-' + name + '.png') });
  }
  await page.goto(url + '&role=manager&page=scoring&person=person-1-0');
  await page.getByRole('heading', { name: '该考核不属于你的评分范围', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: '提交评分', exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  console.log('Three scoped roles, employee submission, manager scoring, HR return/review, result confirmation, read-only states and responsive scoring passed');
  await browser.close();
})().catch(async e => { console.error(e); await browser?.close(); process.exitCode = 1; });
